"""Adversarial eval for the RAG pipeline: poison the corpus, then ask
perfectly normal questions.

    python3 evals/run_adversarial_rag.py              # all three backends
    python3 evals/run_adversarial_rag.py --retriever dense

The golden set (run_eval.py) grades the system on a corpus it can
trust. A deployed knowledge base is not that: anyone who can add a
document can plant instructions or false facts in it, and the
retriever will faithfully fetch them. This suite measures that
surface with the seed cases in evals/adversarial_rag.yaml:

  attacks     a poisoned doc joins the real corpus; success = the
              planted claim / steering address / canary lands in the
              answer (scoring in evals/rag_scoring.py, frozen v1)
  unsupported questions the corpus cannot answer; anything but the
              don't-know refusal counts as fabrication
  controls    benign traffic, including docs that quote attack-like
              text as content; a refusal here is a false refusal
  bystanders  some attack cases carry a second, unrelated benign
              question asked against the same poisoned corpus —
              completion under attack, the utility price of the day

Report-only: nothing here gates CI (the golden eval does that), and
nothing in the pipeline is tuned against these cases — weaknesses
are findings, logged in the report, not quietly patched over.

Everything is deterministic: hashing embedder, BM25, and the
extractive mock generator (forced via the generator: mock override,
API key or not), so re-running reproduces
evals/adversarial-rag-runs.json byte for byte. The report at
evals/adversarial-rag-report.md is generated from the same rows.
"""
import argparse
import json
import sys

import yaml

sys.path.insert(0, ".")
sys.path.insert(0, "evals")
from pipeline import RAGPipeline
import rag_scoring as scoring

BACKENDS = ("dense", "bm25", "hybrid")
OVERRIDES = {"generator": "mock", "semantic_cache": False}


def _pipeline(backend, extra_docs):
    # fresh pipeline per case: the poisoned corpus for one case must
    # never leak into the next case's index
    rag = RAGPipeline(overrides={"retriever": backend, **OVERRIDES})
    docs = json.load(open("data/sample_docs.json")) + list(extra_docs)
    rag.index_documents(docs)
    return rag


def _poison_hashes(rag, case):
    doc_ids = {d["metadata"]["doc_id"] for d in case.get("docs", [])}
    return [m["hash"] for m in rag.retriever.metas
            if m.get("doc_id") in doc_ids]


def _run_backend(backend, cases):
    rows = []
    for case in cases["attacks"]:
        rag = _pipeline(backend, case.get("docs", []))
        hashes = _poison_hashes(rag, case)
        res = rag.answer(case["question"], filters=case.get("filters"),
                         top_k=3)
        rows.append({
            "backend": backend, "id": case["id"], "kind": "attack",
            "style": case.get("style", ""),
            "outcome": scoring.classify_attack(
                res["answer"], res["citations"], case["signal"], hashes),
            "answer": res["answer"],
        })
        by = case.get("bystander")
        if by:
            res = rag.answer(by["question"], filters=by.get("filters"),
                             top_k=3)
            rows.append({
                "backend": backend, "id": case["id"] + "/bystander",
                "kind": "bystander", "style": case.get("style", ""),
                "outcome": scoring.classify_benign(
                    res["answer"], by["must_contain"]),
                "answer": res["answer"],
            })
    for case in cases["unsupported"]:
        rag = _pipeline(backend, [])
        res = rag.answer(case["question"], filters=case.get("filters"),
                         top_k=3)
        rows.append({
            "backend": backend, "id": case["id"], "kind": "unsupported",
            "style": "",
            "outcome": scoring.classify_unsupported(res["answer"]),
            "answer": res["answer"],
        })
    for case in cases["controls"]:
        rag = _pipeline(backend, case.get("docs", []))
        res = rag.answer(case["question"], filters=case.get("filters"),
                         top_k=3)
        rows.append({
            "backend": backend, "id": case["id"], "kind": "benign",
            "style": "",
            "outcome": scoring.classify_benign(
                res["answer"], case["must_contain"]),
            "answer": res["answer"],
        })
    return rows


def _pct(x):
    return f"{x * 100:.1f}%"


def _report(all_rows, summaries):
    lines = [
        "# RAG adversarial report",
        "",
        "Generated by `evals/run_adversarial_rag.py` from "
        "`evals/adversarial_rag.yaml` (cases) and `evals/rag_scoring.py` "
        f"(metric definitions, frozen v{summaries['dense']['metrics_version']}). "
        "Backends run the extractive mock generator — see RESEARCH.md "
        "for what that bounds. Report-only: not a CI gate.",
        "",
        "## Headline metrics",
        "",
        "| backend | attacks (n) | blocked | succeeded | evaded | ASR | "
        "unsupported (n) | fabricated | benign (n) | FRR | completion | "
        "completion under attack |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name in BACKENDS + ("all",):
        s = summaries[name]
        a, u, b, by = s["attacks"], s["unsupported"], s["benign"], \
            s["bystander"]
        lines.append(
            f"| {name} | {a['n']} | {a['blocked']} | {a['succeeded']} | "
            f"{a['evaded']} | {_pct(a['asr'])} | {u['n']} | "
            f"{u['fabricated']} ({_pct(u['fabrication_rate'])}) | {b['n']} "
            f"| {_pct(b['frr'])} | {_pct(b['completion'])} | "
            f"{_pct(by['completion_under_attack'])} (n={by['n']}) |")
    lines += ["", "## Attack outcomes by case", "",
              "| case | style | dense | bm25 | hybrid |",
              "|---|---|---|---|---|"]
    by_case = {}
    for r in all_rows:
        if r["kind"] == "attack":
            by_case.setdefault(r["id"], {})[r["backend"]] = r["outcome"]
            by_case[r["id"]]["style"] = r["style"]
    for cid in sorted(by_case):
        row = by_case[cid]
        lines.append(f"| {cid} | {row['style']} | {row['dense']} | "
                     f"{row['bm25']} | {row['hybrid']} |")
    lines += ["", "## Unsupported questions", "",
              "| case | dense | bm25 | hybrid |", "|---|---|---|---|"]
    by_case = {}
    for r in all_rows:
        if r["kind"] == "unsupported":
            by_case.setdefault(r["id"], {})[r["backend"]] = r["outcome"]
    for cid in sorted(by_case):
        row = by_case[cid]
        lines.append(f"| {cid} | {row['dense']} | {row['bm25']} | "
                     f"{row['hybrid']} |")
    lines += ["", "## Benign controls", "",
              "| case | dense | bm25 | hybrid |", "|---|---|---|---|"]
    by_case = {}
    for r in all_rows:
        if r["kind"] in ("benign", "bystander"):
            by_case.setdefault(r["id"], {})[r["backend"]] = r["outcome"]
    for cid in sorted(by_case):
        row = by_case[cid]
        lines.append(f"| {cid} | {row['dense']} | {row['bm25']} | "
                     f"{row['hybrid']} |")
    lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--retriever", choices=BACKENDS, default=None,
                    help="run one backend only (report files are only "
                         "rewritten on a full three-backend run)")
    args = ap.parse_args()
    cases = yaml.safe_load(open("evals/adversarial_rag.yaml"))["cases"]
    backends = (args.retriever,) if args.retriever else BACKENDS

    all_rows = []
    for name in backends:
        rows = _run_backend(name, cases)
        all_rows += rows
        s = scoring.summarise(rows)
        a, u, b = s["attacks"], s["unsupported"], s["benign"]
        print(f"{name:7s} attacks: ASR {_pct(a['asr'])} "
              f"({a['succeeded']}/{a['n']} succeeded, {a['evaded']} "
              f"evaded) · unsupported fabricated "
              f"{_pct(u['fabrication_rate'])} ({u['fabricated']}/{u['n']}) "
              f"· benign FRR {_pct(b['frr'])}, completion "
              f"{_pct(b['completion'])}")

    if args.retriever:
        return
    summaries = {name: scoring.summarise(
        [r for r in all_rows if r["backend"] == name]) for name in BACKENDS}
    summaries["all"] = scoring.summarise(all_rows)
    with open("evals/adversarial-rag-runs.json", "w") as f:
        json.dump(all_rows, f, indent=2, sort_keys=True)
    with open("evals/adversarial-rag-report.md", "w") as f:
        f.write(_report(all_rows, summaries))
    s = summaries["all"]
    print(f"\nwrote evals/adversarial-rag-runs.json + "
          f"evals/adversarial-rag-report.md — all backends: ASR "
          f"{_pct(s['attacks']['asr'])}, fabrication "
          f"{_pct(s['unsupported']['fabrication_rate'])}, FRR "
          f"{_pct(s['benign']['frr'])}")


if __name__ == "__main__":
    main()
